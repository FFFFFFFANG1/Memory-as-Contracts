#!/usr/bin/env python3
"""Build and validate MAC contract graphs from generated constraint histories.

Graph construction is deterministic: generated constraints are mapped directly
to ContractGraph nodes, and except_by becomes exception_to edges. For task
sequence inputs, this script first validates the whole chain; if that fails, it
also validates each source constraint graph to locate the bad subgraph.
"""

from __future__ import annotations

import argparse
import json
import sys
from concurrent.futures import ThreadPoolExecutor, as_completed
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[4]
SRC_ROOT = REPO_ROOT / "src"
if str(SRC_ROOT) not in sys.path:
    sys.path.insert(0, str(SRC_ROOT))

from benchmarks.contracts.resolver import resolve  # noqa: E402
from benchmarks.schemas.models import (  # noqa: E402
    CanonicalAction,
    ContractGraph,
)

PREFIX_END_EVENT = 10

@dataclass(frozen=True)
class ValidationJob:
    ordinal: int
    total: int
    artifact: dict[str, Any]


def load_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path: Path, payload: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=4, ensure_ascii=False) + "\n", encoding="utf-8")


def resolve_path(path: Path) -> Path:
    return path if path.is_absolute() else REPO_ROOT / path


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input",
        type=Path,
        default=Path("bench/MAC/cctu/mid_data/eval_step2_rule_graphs.json"),
        help="Constraint histories generated by rule_graph.py.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("bench/MAC/cctu/mid_data/eval_step2_rule_graphs.validated.json"),
        help="Output JSON containing deterministically built graphs and validation results.",
    )
    parser.add_argument("--limit", type=int, default=None, help="Validate at most N artifacts.")
    parser.add_argument("--offset", type=int, default=0, help="Start from this artifact offset.")
    parser.add_argument("--workers", type=int, default=1, help="Number of graphs to process in parallel.")
    return parser.parse_args()


def selected_items(data: list[dict[str, Any]], offset: int, limit: int | None) -> list[dict[str, Any]]:
    if offset < 0:
        raise ValueError("--offset must be non-negative")
    if limit is not None and limit < 0:
        raise ValueError("--limit must be non-negative")
    end = None if limit is None else offset + limit
    return data[offset:end]


def graph_id_for_artifact(artifact: dict[str, Any]) -> str:
    if artifact.get("chain_level"):
        return f"graph-{artifact.get('task_uid')}-chain"
    return f"graph-{artifact.get('constraint_uid')}"


def node_id_for_item(constraint_uid: str, item: dict[str, Any]) -> str:
    if item.get("chain_level_node"):
        return str(item.get("local_id"))
    if item.get("is_anchor"):
        return f"{constraint_uid}-anchor"
    return f"{constraint_uid}-{item.get('local_id')}"


def expected_decisive_node_ids(artifact: dict[str, Any]) -> list[str]:
    if artifact.get("chain_level"):
        return sorted(
            str(item.get("local_id"))
            for item in artifact.get("generated_constraints", [])
            if isinstance(item, dict) and item.get("is_anchor") and item.get("local_id")
        )
    return [f"{artifact.get('constraint_uid')}-anchor"]


def current_scope(artifact: dict[str, Any]) -> dict[str, Any]:
    if artifact.get("chain_level"):
        return {
            "project": artifact.get("task_uid"),
            "task": artifact.get("chain_uid"),
        }
    return {
        "project": artifact.get("task_uid"),
        "task": artifact.get("constraint_uid"),
    }


def proposed_action(artifact: dict[str, Any]) -> CanonicalAction:
    graph_id = graph_id_for_artifact(artifact)
    return CanonicalAction(
        family="command.execute",
        tool="rule_graph_eval",
        target=graph_id,
        object="constraint_application",
        effect_summary="evaluate active scoped constraints",
        scope={},
        arguments={"constraint_uid": artifact.get("constraint_uid"), "task_uid": artifact.get("task_uid")},
    )


def node_scope(artifact: dict[str, Any], item: dict[str, Any]) -> dict[str, Any]:
    scope = item.get("scope")
    if scope == "global":
        return {}
    if scope == "project":
        return {"project": artifact.get("task_uid")}
    if scope == "phase":
        return {"project": artifact.get("task_uid"), "task": current_scope(artifact)["task"]}
    return {}


def node_lifecycle(item: dict[str, Any]) -> dict[str, Any]:
    if item.get("trigger_condition_holds"):
        return {
            "effective_from_event": 0,
            "effective_until_event": None,
            "until_revoked": True,
            "revoked_at_event": None,
        }
    return {
        "effective_from_event": 0,
        "effective_until_event": PREFIX_END_EVENT,
        "until_revoked": True,
        "revoked_at_event": None,
    }


def build_contract_graph_payload(artifact: dict[str, Any]) -> dict[str, Any]:
    constraint_uid = str(artifact.get("constraint_uid"))
    graph_id = graph_id_for_artifact(artifact)
    items = [item for item in artifact.get("generated_constraints", []) if isinstance(item, dict)]
    local_to_node = {
        str(item.get("local_id")): node_id_for_item(constraint_uid, item)
        for item in items
        if item.get("local_id")
    }

    nodes = []
    for item in items:
        local_id = str(item.get("local_id", ""))
        nodes.append(
            {
                "id": local_to_node.get(local_id, node_id_for_item(constraint_uid, item)),
                "surface_text": str(item.get("text", "")),
                "modality": "must",
                "action_predicate": {
                    "family": "command.execute",
                    "object": "constraint_application",
                    "target": graph_id,
                },
                "scope": node_scope(artifact, item),
                "lifecycle": node_lifecycle(item),
                "source_turn_ids": [str(artifact.get("task_uid")), constraint_uid],
                "directness": "embedded",
                "authority": 1 if item.get("is_anchor") else 0,
                "blueprint_id": local_id,
            }
        )

    edges = []
    for index, item in enumerate(items, start=1):
        except_by = item.get("except_by")
        if except_by in {None, ""}:
            continue
        source = local_to_node.get(str(except_by))
        target = local_to_node.get(str(item.get("local_id")))
        if not source or not target:
            continue
        edges.append(
            {
                "id": f"{constraint_uid}-e{index:03d}",
                "type": "exception_to",
                "source": source,
                "target": target,
                "surface_text": f"{source} suppresses {target}",
            }
        )

    return {"contract_graph": {"graph_id": graph_id, "nodes": nodes, "edges": edges}}


def validate_graph_payload(artifact: dict[str, Any], graph_payload: dict[str, Any]) -> dict[str, Any]:
    errors: list[str] = []
    warnings: list[str] = []
    graph_raw = graph_payload.get("contract_graph", graph_payload)
    try:
        graph = ContractGraph.model_validate(graph_raw)
    except Exception as exc:  # noqa: BLE001 - validation should be reported in output.
        return {
            "accepted": False,
            "errors": [f"contract graph schema validation failed: {exc}"],
            "warnings": warnings,
            "resolved_active_node_ids": [],
            "decisive_edge_ids": [],
        }

    items = artifact.get("generated_constraints", [])
    expected_node_ids = {
        node_id_for_item(str(artifact.get("constraint_uid")), item)
        for item in items
        if isinstance(item, dict)
    }
    actual_node_ids = {node.id for node in graph.nodes}
    if actual_node_ids != expected_node_ids:
        errors.append(
            "graph node IDs must match generated constraints; "
            f"missing={sorted(expected_node_ids - actual_node_ids)} extra={sorted(actual_node_ids - expected_node_ids)}"
        )

    anchor_items = [item for item in items if isinstance(item, dict) and item.get("is_anchor")]
    if artifact.get("chain_level"):
        if not anchor_items:
            errors.append("expected at least one anchor item for chain-level graph")
    elif len(anchor_items) != 1:
        errors.append(f"expected exactly one anchor item, got {len(anchor_items)}")

    expected_exception_edges = []
    local_to_node = {
        str(item.get("local_id")): node_id_for_item(str(artifact.get("constraint_uid")), item)
        for item in items
        if isinstance(item, dict)
    }
    for item in items:
        if not isinstance(item, dict) or not item.get("except_by"):
            continue
        source = local_to_node.get(str(item.get("except_by")))
        target = local_to_node.get(str(item.get("local_id")))
        if source and target:
            expected_exception_edges.append((source, target))
        else:
            errors.append(
                f"except_by on {item.get('local_id')} references unknown local_id {item.get('except_by')}"
            )

    actual_exception_edges = {
        (edge.source, edge.target)
        for edge in graph.edges
        if edge.type == "exception_to"
    }
    for source, target in expected_exception_edges:
        if (source, target) not in actual_exception_edges:
            errors.append(f"missing exception_to edge {source} -> {target}")

    try:
        decision = resolve(
            graph,
            prefix_end_event=PREFIX_END_EVENT,
            current_scope=current_scope(artifact),
            proposed_action=proposed_action(artifact),
        )
        decisive_ids = decision.decisive_contract_ids
        decisive_edge_ids = decision.decisive_relation_ids
        expected_decisive_ids = expected_decisive_node_ids(artifact)
        if decisive_ids != expected_decisive_ids:
            errors.append(
                "graph must resolve to expected decisive active node ids; "
                f"got {decisive_ids}"
            )
    except Exception as exc:  # noqa: BLE001 - validation should return structured errors.
        decisive_ids = []
        decisive_edge_ids = []
        errors.append(f"local graph resolution failed: {exc}")

    return {
        "accepted": not errors,
        "errors": errors,
        "warnings": warnings,
        "resolved_active_node_ids": decisive_ids,
        "decisive_edge_ids": decisive_edge_ids,
    }


def per_constraint_artifacts_from_chain(artifact: dict[str, Any]) -> list[dict[str, Any]]:
    by_constraint: dict[str, list[dict[str, Any]]] = {}
    for item in artifact.get("generated_constraints", []):
        if not isinstance(item, dict):
            continue
        source_uid = item.get("source_constraint_uid")
        if not source_uid:
            continue
        by_constraint.setdefault(str(source_uid), []).append(item)

    artifacts: list[dict[str, Any]] = []
    for constraint_uid, items in sorted(by_constraint.items()):
        generated_constraints = []
        for item in items:
            copied = dict(item)
            copied.pop("chain_level_node", None)
            generated_constraints.append(copied)
        artifacts.append(
            {
                "task_uid": artifact.get("task_uid"),
                "constraint_uid": constraint_uid,
                "chain_level": False,
                "constraint_text": f"per-constraint fallback for {constraint_uid}",
                "anchor_role": "per_constraint",
                "anchor_scope": "per_constraint",
                "generated_constraints": generated_constraints,
            }
        )
    return artifacts


def validate_artifact(artifact: dict[str, Any]) -> tuple[dict[str, Any], dict[str, Any]]:
    graph_payload = build_contract_graph_payload(artifact)
    validation = validate_graph_payload(artifact, graph_payload)
    graph_raw = graph_payload.get("contract_graph", graph_payload)
    return graph_raw, validation


def process_job(job: ValidationJob, args: argparse.Namespace) -> dict[str, Any]:
    artifact = job.artifact
    print(
        f"validating graph {job.ordinal}/{job.total} "
        f"task={artifact.get('task_uid')} constraint={artifact.get('constraint_uid')} "
        f"role={artifact.get('anchor_role')}",
        flush=True,
    )
    graph_raw, validation = validate_artifact(artifact)

    per_constraint_diagnostics = []
    if artifact.get("chain_level") and not validation.get("accepted"):
        for sub_artifact in per_constraint_artifacts_from_chain(artifact):
            sub_graph, sub_validation = validate_artifact(sub_artifact)
            per_constraint_diagnostics.append(
                {
                    "constraint_uid": sub_artifact.get("constraint_uid"),
                    "accepted": sub_validation.get("accepted"),
                    "errors": sub_validation.get("errors", []),
                    "resolved_active_node_ids": sub_validation.get("resolved_active_node_ids", []),
                    "expected_active_node_ids": expected_decisive_node_ids(sub_artifact),
                    "node_count": len(sub_graph.get("nodes", [])) if isinstance(sub_graph, dict) else 0,
                }
            )

    return {
        **artifact,
        "contract_graph": graph_raw,
        "graph_generation": {
            "method": "deterministic",
            "warnings": [],
        },
        "validation": validation,
        "per_constraint_diagnostics": per_constraint_diagnostics,
        "oracle": {
            "expected_active_node_ids": expected_decisive_node_ids(artifact),
            "decisive_edge_ids": validation.get("decisive_edge_ids", []),
        },
    }


def extract_artifacts(payload: Any) -> list[dict[str, Any]]:
    if isinstance(payload, list):
        return [item for item in payload if isinstance(item, dict)]
    if not isinstance(payload, dict):
        raise ValueError("Expected input JSON object or list")
    if isinstance(payload.get("task_sequences"), list):
        artifacts: list[dict[str, Any]] = []
        for task in payload["task_sequences"]:
            if not isinstance(task, dict):
                continue
            task_uid = str(task.get("task_uid", ""))
            chain_uid = f"{task_uid}-chain"
            sequence = []
            for item in task.get("constraint_sequence", []):
                if not isinstance(item, dict):
                    continue
                copied = dict(item)
                copied["chain_level_node"] = True
                sequence.append(copied)
            artifacts.append(
                {
                    "task_uid": task_uid,
                    "constraint_uid": chain_uid,
                    "chain_uid": chain_uid,
                    "chain_level": True,
                    "agent_name": task.get("agent_name"),
                    "task_level": task.get("task_level"),
                    "source_graph_count": task.get("source_graph_count"),
                    "constraint_sequence_count": task.get("constraint_sequence_count"),
                    "constraint_text": f"chain-level validation for {task_uid}",
                    "anchor_role": "chain",
                    "anchor_scope": "chain",
                    "generated_constraints": sequence,
                }
            )
        return artifacts
    raw = payload.get("constraint_histories", payload.get("graphs", []))
    if not isinstance(raw, list):
        raise ValueError("Input must contain constraint_histories or graphs list")
    return [item for item in raw if isinstance(item, dict)]


def iter_jobs(artifacts: list[dict[str, Any]]) -> list[ValidationJob]:
    total = len(artifacts)
    return [
        ValidationJob(ordinal=index, total=total, artifact=artifact)
        for index, artifact in enumerate(artifacts, start=1)
    ]


def summarize(results: list[dict[str, Any]]) -> dict[str, Any]:
    accepted = 0
    role_counts: dict[str, int] = {}
    edge_counts: dict[str, int] = {}
    for result in results:
        role = str(result.get("anchor_role"))
        role_counts[role] = role_counts.get(role, 0) + 1
        validation = result.get("validation", {})
        if isinstance(validation, dict) and validation.get("accepted"):
            accepted += 1
        graph = result.get("contract_graph")
        if isinstance(graph, dict):
            for edge in graph.get("edges", []):
                if isinstance(edge, dict):
                    edge_type = str(edge.get("type"))
                    edge_counts[edge_type] = edge_counts.get(edge_type, 0) + 1
    return {
        "total_graphs": len(results),
        "accepted_graphs": accepted,
        "rejected_graphs": len(results) - accepted,
        "role_distribution": role_counts,
        "edge_distribution": edge_counts,
    }


def main() -> int:
    args = parse_args()
    input_path = resolve_path(args.input)
    output_path = resolve_path(args.output)
    payload = load_json(input_path)
    artifacts = selected_items(extract_artifacts(payload), args.offset, args.limit)
    jobs = iter_jobs(artifacts)
    workers = max(1, int(args.workers))
    results: list[dict[str, Any]] = []

    if workers == 1:
        for job in jobs:
            results.append(process_job(job, args))
    else:
        with ThreadPoolExecutor(max_workers=workers) as executor:
            futures = [executor.submit(process_job, job, args) for job in jobs]
            for future in as_completed(futures):
                results.append(future.result())
        results.sort(key=lambda artifact: (artifact.get("task_uid", ""), artifact.get("constraint_uid", "")))

    summary = summarize(results)
    output_payload = {
        "source_input": str(args.input),
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "summary": summary,
        "graphs": results,
    }
    write_json(output_path, output_payload)
    print(
        f"wrote {len(results)} validated graph artifact(s), "
        f"accepted={summary['accepted_graphs']}, rejected={summary['rejected_graphs']}, "
        f"output={output_path}"
    )
    return 0 if summary["rejected_graphs"] == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
